#ifndef CAMERA_APP_H
#define CAMERA_APP_H

#include "camera_drv.h"
#include <stdbool.h>

/**********************************************************************************************************************
 * CEU 采集缓冲大小：320 x 240 x 2 字节（YCbCr422, QVGA —— 匹配 OV7725 实际输出）
 **********************************************************************************************************************/
#define CAMERA_IMAGE_W              (640U)
#define CAMERA_IMAGE_H              (480U)
#define CAMERA_IMAGE_SIZE           (CAMERA_IMAGE_W * CAMERA_IMAGE_H * 2U)

/**********************************************************************************************************************
 * 外部变量：CEU 双采集缓冲（32 字节对齐，满足 CEU DMA/突发传输要求）& 就绪标志
 **********************************************************************************************************************/
extern uint8_t g_ceu_buffer_0[CAMERA_IMAGE_SIZE] __attribute__((aligned(32)));
extern uint8_t g_ceu_buffer_1[CAMERA_IMAGE_SIZE] __attribute__((aligned(32)));
extern volatile bool g_frame_ready;

/**********************************************************************************************************************
 * OV7725 寄存器表类型
 **********************************************************************************************************************/
typedef struct
{
    uint8_t reg;
    uint8_t val;
} ov7725_reg_t;

/**********************************************************************************************************************
 * 函数声明
 **********************************************************************************************************************/
bool camera_ov7725_init(void);
bool camera_app_init(void);   /* true=就绪, false=失败(不再死循环) */

void camera_app_request_capture(bool enable);
bool camera_app_service_capture(void);
bool camera_app_capture_active(void);

/**********************************************************************************************************************
 * 实测帧率（×10 定点，99 = 9.9 FPS）
 *  - camera_app_get_fps_x10():      采集激活期间的实时值；停止后为 0
 *  - camera_app_get_last_fps_x10(): 最近一次有效实测值（采集停止后仍保留）
 **********************************************************************************************************************/
void camera_app_update_fps(void);
uint32_t camera_app_get_fps_x10(void);
uint32_t camera_app_get_last_fps_x10(void);

#endif /* CAMERA_APP_H */
