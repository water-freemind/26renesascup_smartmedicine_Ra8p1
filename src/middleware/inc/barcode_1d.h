#ifndef BARCODE_1D_H
#define BARCODE_1D_H

#include <stdbool.h>
#include <stdint.h>

/**********************************************************************************************************************
 * EAN-13 一维条码解码器（药品商品条码）
 *
 * 输入：单帧灰度（复用 QR 链路的 s_gray 快照），多行扫描。
 * 输出：13 位数字字符串（NUL 结尾，含校验位）或失败。
 *
 * 设计：
 *  - 水平多行扫描（每 SCAN_ROW_STEP 像素取一行），条码平放/接近水平即可；
 *  - 每行做完整 EAN-13 结构解析（起始/中间/结束 guard + L/G/R 码 + 校验位），
 *    错码/校验失败自动丢弃，不产生误报；
 *  - 正反双向：OV7725 COM3=0x50 配置 HFLIP（画面水平镜像），EAN-13 无镜像
 *    对称性（L/G/R 三套码），镜像条码必须整行像素反转恢复正向才能解码；
 *  - 阈值：行内均值动态二值化（条码对比度通常足够高）。
 *
 * 内存：无堆分配；行缓冲局部数组（<1KB 栈）。
 **********************************************************************************************************************/

/* EAN-13 数字位数（含校验位） */
#define EAN13_DIGITS      (13U)
/* 输出缓冲建议：EAN13_DIGITS + 1（NUL） */
#define EAN13_TEXT_MAX    (EAN13_DIGITS + 1U)

/* 水平扫描行间隔（像素）：条码高度通常 >50px，步进 4 覆盖整幅 */
#define EAN13_SCAN_ROW_STEP (4U)

/**********************************************************************************************************************
 * 解码一帧灰度（w x h）中的 EAN-13。
 * @param p_gray  灰度帧（w*h，同 QR 链路 s_gray 格式）
 * @param w, h    帧尺寸
 * @param p_out   输出缓冲 ≥ EAN13_TEXT_MAX，成功时写入 13 位数字 + NUL
 * @return true 找到并校验通过的 EAN-13；false 未识别
 **********************************************************************************************************************/
bool ean13_decode_frame(const uint8_t * p_gray, uint32_t w, uint32_t h,
                        char * p_out);

#endif /* BARCODE_1D_H */
